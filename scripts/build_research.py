"""Build learn/research.html: every paper, repo and doc cited in the chapters'
"Where to go deeper" sections, as bullet points with links, grouped by chapter.

Run from the repository root:
    python3 scripts/build_research.py
"""
import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEARN = ROOT / "learn"
ORDER = re.findall(r'\("([a-z-]+\.html)", "([^"]+)"', (ROOT / "scripts" / "fix_nav.py").read_text())
SKIP = {"notes.html", "flashcards.html", "gallery.html", "research.html", "sources.html"}

def deeper_section(page_html):
    m = re.search(r'<h2[^>]*>[^<]*(?:go deeper|Where to go|deeper)[^<]*</h2>(.*?)(?=<div class="footer-nav"|<h2|</main>)', page_html, re.S | re.I)
    return m.group(1) if m else ""

def items(section):
    out = []
    for li in re.findall(r'<li[^>]*>(.*?)</li>', section, re.S):
        links = re.findall(r'<a href="(https?://[^"]+)"[^>]*>(.*?)</a>', li, re.S)
        if not links:
            continue
        text = re.sub(r'<[^>]+>', '', li)
        text = re.sub(r'\s+', ' ', html.unescape(text)).strip()
        out.append((links, text))
    return out

sections = []
total = 0
for href, title in ORDER:
    if href in SKIP or not (LEARN / href).exists():
        continue
    its = items(deeper_section((LEARN / href).read_text()))
    if not its:
        continue
    total += len(its)
    lis = []
    for links, text in its:
        anchors = " · ".join(f'<a href="{html.escape(u)}">{re.sub(r"<[^>]+>", "", t).strip() or u}</a>' for u, t in links)
        # the bullet text without duplicating the link labels
        note = text
        for _, t in links:
            note = note.replace(re.sub(r"<[^>]+>", "", t).strip(), "", 1)
        note = re.sub(r'^[\s\-–—·,:;]+|[\s\-–—·,:;]+$', '', note)
        lis.append(f"<li>{anchors}{(' — ' + html.escape(note)) if note else ''}</li>")
    sections.append(f'<h2 id="{href[:-5]}">{html.escape(title.replace("&amp;", "&"))} <span class="dim">(<a href="{href}">chapter</a>)</span></h2>\n<ul>{"".join(lis)}</ul>')

page = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Research Reading List</title><link rel="stylesheet" href="learn.css">
<style>ul{{padding-left:1.2em}} li{{margin:4px 0}} .toc a{{margin-right:10px;font-size:.9rem}}</style></head><body>
<nav class="topnav"><a class="home" href="index.html">Learn</a><div class="links"><a href="research.html" class="here">Research</a><a href="index.html">All chapters</a><a href="notes.html">Notes library</a></div><div class="spacer"></div><button class="theme-btn" id="themeBtn">◐ theme</button></nav>
<main>
<h1>Research reading list</h1>
<p>Every paper, report, repository and doc the chapters point to — {total} entries as bullet points with links, grouped by chapter and in the order the chapters recommend them. Generated by <code>scripts/build_research.py</code> from each chapter's "where to go deeper" section, so it stays in sync. Read the chapter first; it tells you what each source contributed.</p>
<p class="toc">{' '.join(f'<a href="#{h[:-5]}">{html.escape(t.replace("&amp;", "&"))}</a>' for h, t in ORDER if h not in SKIP and (LEARN / h).exists())}</p>
{chr(10).join(sections)}
</main>
<script>(function(){{const b=document.getElementById('themeBtn');function cur(){{try{{return localStorage.getItem('learn-theme')||'dark'}}catch(e){{return 'dark'}}}}
function apply(t){{document.documentElement.dataset.theme=t;try{{localStorage.setItem('learn-theme',t)}}catch(e){{}}}}
apply(cur());b.onclick=()=>apply(document.documentElement.dataset.theme==='light'?'dark':'light');}})();</script>
</body></html>"""
(LEARN / "research.html").write_text(page)
print(f"wrote learn/research.html: {total} entries across {len(sections)} chapters")
