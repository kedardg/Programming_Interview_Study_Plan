"""Build learn/gallery.html and learn/gallery-data.js from the vendored
LLM Architecture Gallery metadata (learn/vendor/llm-architecture-gallery/models.yml,
Apache-2.0, Sebastian Raschka).

Run from the repository root:

    python3 scripts/build_gallery.py

gallery-data.js also carries per-year adoption statistics used by the
architectures chapter's "what the data says" chart.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "learn" / "vendor" / "llm-architecture-gallery" / "models.yml"
OUT_HTML = ROOT / "learn" / "gallery.html"
OUT_JS = ROOT / "learn" / "gallery-data.js"

data = yaml.safe_load(SRC.read_text())

def s(x):
    return "" if x is None else str(x)

def family(decoder_type):
    d = decoder_type.lower()
    if "hybrid" in d or "recurrent" in d:
        return "Hybrid / recurrent"
    if "moe" in d:
        return "Sparse MoE"
    return "Dense"

# feature detection across free-text fields (related_concepts is only present for ~40% of entries)
FEATURES = {
    "MoE": lambda m, t: "moe" in m.get("decoder_type", "").lower(),
    "Hybrid (SSM / linear attn)": lambda m, t: family(m.get("decoder_type", "")) == "Hybrid / recurrent" or re.search(r"deltanet|mamba|delta attention|shortconv|linear attention", t) is not None,
    "GQA": lambda m, t: "gqa" in t,
    "MLA": lambda m, t: re.search(r"\bmla\b|latent attention", t) is not None,
    "Sliding window": lambda m, t: re.search(r"sliding|\bswa\b|window", t) is not None,
    "QK-Norm": lambda m, t: "qk-norm" in t or "qk_norm" in t or "qk norm" in t,
    "MTP": lambda m, t: re.search(r"\bmtp\b|multi-token prediction", t) is not None,
    "NoPE / partial RoPE": lambda m, t: re.search(r"\bnope\b|no positional", t) is not None,
    "Gated attention": lambda m, t: "gated attention" in t or "gated_attention" in t,
    "Sparse attention (DSA etc.)": lambda m, t: re.search(r"sparse attention|sparse_attention|sparse-index|indexer", t) is not None,
}

models = []
by_year = defaultdict(lambda: {"n": 0, "features": defaultdict(int)})
for name, m in data.items():
    text = " ".join([
        s(m.get("decoder_type")), s(m.get("attention")), s(m.get("layer_mix")),
        s(m.get("highlight")), s(m.get("summary")), " ".join(m.get("related_concepts") or []),
    ]).lower()
    feats = [f for f, fn in FEATURES.items() if fn(m, text)]
    year = s(m.get("date"))[:4]
    by_year[year]["n"] += 1
    for f in feats:
        by_year[year]["features"][f] += 1
    models.append({
        "name": name,
        "company": s(m.get("company")),
        "date": s(m.get("date")),
        "year": year,
        "image": s(m.get("image")),
        "summary": s(m.get("summary")),
        "scale": s(m.get("scale")),
        "context": s(m.get("context_tokens")),
        "vocab": s(m.get("vocab_size")),
        "license": s(m.get("license_name")),
        "decoder": s(m.get("decoder_type")),
        "family": family(s(m.get("decoder_type"))),
        "attention": s(m.get("attention")),
        "layers": s(m.get("layer_mix")),
        "kv": s(m.get("kv_cache_per_token_bf16")),
        "highlight": s(m.get("highlight")),
        "concepts": m.get("related_concepts") or [],
        "features": feats,
        "aa": s(m.get("aa_intelligence_index")),
        "config": (m.get("config") or {}).get("url", ""),
        "report": (m.get("tech_report") or {}).get("url", ""),
    })
models.sort(key=lambda x: x["date"], reverse=True)

adoption = {
    "years": sorted(y for y in by_year if y),
    "features": list(FEATURES.keys()),
    "counts": {y: dict(v["features"]) for y, v in by_year.items()},
    "totals": {y: v["n"] for y, v in by_year.items()},
}

OUT_JS.write_text(
    "// Generated by scripts/build_gallery.py from learn/vendor/llm-architecture-gallery/models.yml\n"
    "// Data: Sebastian Raschka, LLM Architecture Gallery (Apache-2.0).\n"
    "window.GALLERY = " + json.dumps(models, ensure_ascii=False) + ";\n"
    "window.ADOPTION = " + json.dumps(adoption, ensure_ascii=False) + ";\n"
)

